using System.Net;
using System.Net.Http.Json;
using MiniGarage.Api.DTOs;
using MiniGarage.Api.Models;
using Xunit;

namespace MiniGarage.Api.Tests;

/// <summary>
/// Security-focused tests covering:
/// - OWASP API Security Top 10 (2023) mitigations
/// - Security Response Headers (CSP, nosniff, DENY)
/// - Function-Level Authorization (Admin Key enforcement)
/// - Input Validation & Mass Assignment Immunity
/// </summary>
public class SecurityTests : IClassFixture<CustomWebApplicationFactory>
{
    private readonly HttpClient _client;

    public SecurityTests(CustomWebApplicationFactory factory)
    {
        _client = factory.CreateClient();
    }

    // ─────────────────────────────────────────────────────────────
    // OWASP API8:2023 - Security Misconfiguration / Headers
    // ─────────────────────────────────────────────────────────────
    [Fact]
    public async Task Response_Includes_AllMandatorySecurityHeaders()
    {
        // Act
        var response = await _client.GetAsync("/api/cars");

        // Assert
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        // 1. Content Security Policy
        Assert.True(response.Headers.Contains("Content-Security-Policy"), "Missing Content-Security-Policy header");
        var csp = string.Join(" ", response.Headers.GetValues("Content-Security-Policy"));
        Assert.Contains("default-src 'self'", csp);
        Assert.Contains("frame-ancestors 'none'", csp);

        // 2. MIME sniffing protection
        Assert.True(response.Headers.Contains("X-Content-Type-Options"), "Missing X-Content-Type-Options header");
        Assert.Equal("nosniff", response.Headers.GetValues("X-Content-Type-Options").First());

        // 3. Clickjacking protection
        Assert.True(response.Headers.Contains("X-Frame-Options"), "Missing X-Frame-Options header");
        Assert.Equal("DENY", response.Headers.GetValues("X-Frame-Options").First());

        // 4. Referrer Policy
        Assert.True(response.Headers.Contains("Referrer-Policy"), "Missing Referrer-Policy header");
        Assert.Equal("strict-origin-when-cross-origin", response.Headers.GetValues("Referrer-Policy").First());

        // 5. Permissions Policy
        Assert.True(response.Headers.Contains("Permissions-Policy"), "Missing Permissions-Policy header");
    }

    // ─────────────────────────────────────────────────────────────
    // OWASP API5:2023 - Broken Function Level Authorization
    // ─────────────────────────────────────────────────────────────
    [Fact]
    public async Task DeleteEndpoint_WithoutAdminKey_Returns401Unauthorized()
    {
        // Act: Attempt to delete a car without the administrative header
        var response = await _client.DeleteAsync("/api/cars/1");

        // Assert
        Assert.Equal(HttpStatusCode.Unauthorized, response.StatusCode);
    }

    [Fact]
    public async Task DeleteEndpoint_WithWrongAdminKey_Returns401Unauthorized()
    {
        // Act: Attempt deletion with an incorrect or forged admin key
        var request = new HttpRequestMessage(HttpMethod.Delete, "/api/cars/1");
        request.Headers.Add("X-Admin-Key", "forged-or-invalid-token-12345");
        var response = await _client.SendAsync(request);

        // Assert
        Assert.Equal(HttpStatusCode.Unauthorized, response.StatusCode);
    }

    // ─────────────────────────────────────────────────────────────
    // OWASP API3:2023 - Broken Object Property Level Authorization
    // (Mass Assignment & Parameter Tampering)
    // ─────────────────────────────────────────────────────────────
    [Fact]
    public async Task CreateCar_DoesNotAllowClientToOverwriteIdOrCreatedAt()
    {
        // Arrange: Attacker attempts mass assignment by injecting arbitrary Id and historical CreatedAt
        var clientProvidedTime = new DateTime(1999, 1, 1, 0, 0, 0, DateTimeKind.Utc);
        var payload = new
        {
            Id = 99999,
            OwnerName = "Security Tester",
            CarModel = "Tesla Model 3",
            LicensePlate = "SEC-1010",
            ProblemDescription = "Testing mass assignment immunity",
            RepairStatus = 0,
            CreatedAt = clientProvidedTime
        };

        // Act
        var response = await _client.PostAsJsonAsync("/api/cars", payload);

        // Assert
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var created = await response.Content.ReadFromJsonAsync<CarResponseDto>();
        Assert.NotNull(created);

        // Id must be assigned by the server, NOT taken from the client payload
        Assert.NotEqual(99999, created.Id);

        // CreatedAt must be generated by the server (recently), NOT the attacker's 1999 timestamp
        Assert.True(created.CreatedAt.Year >= 2026, "CreatedAt was improperly overwritten by client payload!");
    }

    // ─────────────────────────────────────────────────────────────
    // OWASP API8:2023 & Injection - Input Validation
    // ─────────────────────────────────────────────────────────────
    [Theory]
    [InlineData("PLATE<script>alert(1)</script>")]
    [InlineData("PLATE'; DROP TABLE Cars;--")]
    [InlineData("PLATE$#@*!")]
    public async Task CreateCar_WithMaliciousLicensePlateCharacters_ReturnsBadRequest(string maliciousPlate)
    {
        // Arrange
        var newCar = new CreateCarDto
        {
            OwnerName = "Legitimate Owner",
            CarModel = "Valid Model",
            LicensePlate = maliciousPlate,
            ProblemDescription = "Attempting input validation bypass",
            RepairStatus = RepairStatus.Pending
        };

        // Act
        var response = await _client.PostAsJsonAsync("/api/cars", newCar);

        // Assert
        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }
}
